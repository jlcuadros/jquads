/**
 * Maia-3 input encoding and output decoding (pure functions, no ONNX here).
 *
 * Ported from maiachess.com (CSSLab/maia-platform-frontend, GPL-3.0,
 * commit a6e52f5): src/lib/engine/tensor.ts (boardToMaia3Tokens,
 * preprocessMaia3, mirrorFEN, mirrorMove) and src/lib/engine/maia.ts
 * (processOutputsMaia3). See the task note, Investigation 1.2.
 *
 * Model contract (maia3_simplified.onnx):
 *   inputs : tokens   float32 [B, 64, 12]  one-hot piece per square
 *            elo_self float32 [B]          raw Elo, no bucketing
 *            elo_oppo float32 [B]
 *   outputs: logits_move  [B, 4352]  one logit per move in all_moves_maia3.json
 *            logits_value [B, 3]     loss / draw / win for the side to move
 *
 * The model always "sees" white to move: if black is to move, the position
 * is mirrored (ranks flipped + colours swapped) before encoding, and the
 * predicted moves are mirrored back afterwards.
 */
import { Chess } from 'chess.js'
import allMovesJson from './all_moves_maia3.json'

/** UCI move ("e2e4", "a7a8q") → index in the model's 4352-move output. */
const MOVE_TO_INDEX = allMovesJson as Record<string, number>

/** Inverse of MOVE_TO_INDEX: index → UCI move. */
const INDEX_TO_MOVE: string[] = (() => {
  const arr: string[] = []
  for (const [uci, idx] of Object.entries(MOVE_TO_INDEX)) arr[idx] = uci
  return arr
})()

export const NUM_MOVES = INDEX_TO_MOVE.length // 4352
export const TOKENS_PER_BOARD = 64 * 12

// Channel order expected by the model: white P..K (0-5), black p..k (6-11).
const PIECE_ORDER = 'PNBRQKpnbrqk'

// ---------------------------------------------------------------------------
// Mirroring helpers (used when black is to move)
// ---------------------------------------------------------------------------

/** "e2" → "e7": flips the rank, keeps the file. */
export function mirrorSquare(square: string): string {
  return square[0] + (9 - Number(square[1])).toString()
}

/** "e7e5" → "e2e4"; promotion suffix is kept. */
export function mirrorMove(uci: string): string {
  return mirrorSquare(uci.slice(0, 2)) + mirrorSquare(uci.slice(2, 4)) + uci.slice(4)
}

/** Swaps piece colours in one FEN rank: "rnbQ2" → "RNBq2". */
function swapCase(rank: string): string {
  return rank.replace(/[a-zA-Z]/g, (c) => (c === c.toUpperCase() ? c.toLowerCase() : c.toUpperCase()))
}

/** Swaps castling rights white↔black, keeping the canonical KQkq order. */
function swapCastling(castling: string): string {
  if (castling === '-') return '-'
  const swapped = swapCase(castling)
  const out = 'KQkq'.split('').filter((c) => swapped.includes(c)).join('')
  return out || '-'
}

/**
 * Mirrors a whole FEN vertically and swaps colours, so that a "black to move"
 * position becomes the equivalent "white to move" one.
 */
export function mirrorFen(fen: string): string {
  const [board, turn, castling, ep, half = '0', full = '1'] = fen.split(' ')
  const mirroredBoard = board.split('/').reverse().map(swapCase).join('/')
  const mirroredTurn = turn === 'w' ? 'b' : 'w'
  const mirroredEp = ep && ep !== '-' ? mirrorSquare(ep) : '-'
  return `${mirroredBoard} ${mirroredTurn} ${swapCastling(castling)} ${mirroredEp} ${half} ${full}`
}

// ---------------------------------------------------------------------------
// Encoding
// ---------------------------------------------------------------------------

/**
 * Board part of a FEN → Float32Array(64*12), index = square*12 + piece,
 * with square = rank*8 + file and a1 = 0 (same layout as maiachess).
 */
function boardToTokens(fen: string): Float32Array {
  const tokens = new Float32Array(TOKENS_PER_BOARD)
  const rows = fen.split(' ')[0].split('/') // rows[0] is rank 8
  for (let r = 0; r < 8; r++) {
    const rank = 7 - r
    let file = 0
    for (const ch of rows[r]) {
      const empty = Number(ch)
      if (empty) {
        file += empty
      } else {
        const piece = PIECE_ORDER.indexOf(ch)
        if (piece >= 0) tokens[(rank * 8 + file) * 12 + piece] = 1
        file += 1
      }
    }
  }
  return tokens
}

/** What the model needs for one position, plus what we need to decode it. */
export interface EncodedPosition {
  tokens: Float32Array // model input "tokens" for this board
  legalIndices: number[] // indices (in the 4352 space) of the legal moves
  legalMovesUci: string[] // same moves, in the REAL board orientation
  blackToMove: boolean
}

/**
 * Encodes a FEN for Maia-3. Legal moves are generated by chess.js on the
 * (possibly mirrored) board, mapped to model indices, and mirrored back so
 * the caller always gets moves for the real position.
 */
export function encodePosition(fen: string): EncodedPosition {
  const blackToMove = fen.split(' ')[1] === 'b'
  const modelFen = blackToMove ? mirrorFen(fen) : fen
  const board = new Chess(modelFen)

  const legalIndices: number[] = []
  const legalMovesUci: string[] = []
  for (const m of board.moves({ verbose: true })) {
    const uci = m.from + m.to + (m.promotion ?? '')
    const idx = MOVE_TO_INDEX[uci]
    if (idx === undefined) continue // should not happen; ignore defensively
    legalIndices.push(idx)
    legalMovesUci.push(blackToMove ? mirrorMove(uci) : uci)
  }

  return { tokens: boardToTokens(modelFen), legalIndices, legalMovesUci, blackToMove }
}

// ---------------------------------------------------------------------------
// Decoding
// ---------------------------------------------------------------------------

export interface MaiaPrediction {
  /** Legal moves (UCI) → probability that a human of this Elo plays it, sorted desc. */
  policy: Array<{ uci: string; prob: number }>
  /** Expected score for WHITE (win + ½ draw), 0..1. */
  whiteWinProb: number
}

/** Numerically stable softmax. */
function softmax(values: number[]): number[] {
  const max = Math.max(...values)
  const exps = values.map((v) => Math.exp(v - max))
  const sum = exps.reduce((a, b) => a + b, 0)
  return exps.map((e) => e / sum)
}

/**
 * Turns the raw logits of ONE position into probabilities.
 * @param moveLogits  the 4352 logits of this position
 * @param valueLogits the 3 logits (loss, draw, win) of this position
 */
export function decodePrediction(
  enc: EncodedPosition,
  moveLogits: Float32Array,
  valueLogits: Float32Array,
): MaiaPrediction {
  // Softmax restricted to legal moves only.
  const probs = softmax(enc.legalIndices.map((i) => moveLogits[i]))
  const policy = enc.legalMovesUci
    .map((uci, i) => ({ uci, prob: probs[i] }))
    .sort((a, b) => b.prob - a.prob)

  // Value head: [loss, draw, win] for the side to move → expected score.
  const [, d, w] = softmax(Array.from(valueLogits))
  const sideToMove = w + 0.5 * d
  const whiteWinProb = enc.blackToMove ? 1 - sideToMove : sideToMove

  return { policy, whiteWinProb }
}
