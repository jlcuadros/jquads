// Generates the PUBLIC documentation (docs/) from the private Obsidian notes.
//
// The source of truth is the vault notes (app.md, scripts/scripts.md); they are
// not published (see .gitignore) because they contain Obsidian wikilinks to
// private notes and personal data. This script writes cleaned copies:
//   - [[target|alias]] → alias, [[target#heading]] → "target › heading",
//     [[target]] → target; embedded images ![[...]] are removed;
//   - lines mentioning private data (emails) are redacted;
//   - relative links are rewritten so they work from docs/.
//
// Usage (from app/): node scripts/export-docs.mjs     (run before each commit)
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')

/** source note (relative to app/) → [published file in docs/, link prefix from docs/ to the note's folder] */
const NOTES = [
  ['app.md', 'ARCHITECTURE.md', '../'],
  ['scripts/scripts.md', 'SCRIPTS.md', '../scripts/'],
]

/** Anything that must never be published. */
const PRIVATE = [/[\w.+-]+@[\w-]+\.[\w.]+/g]

/** Private note names → neutral wording in the public docs. */
const NOTE_NAMES = { 'task_02_maia stockfish analysis webapp': "the author's project notes" }
const noteName = (path) => {
  const name = path.split('/').pop()
  return NOTE_NAMES[name] ?? name
}

function clean(md, linkPrefix) {
  return (
    md
      // Embedded images (they live in the private vault).
      .replace(/!\[\[[^\]]*\]\]/g, '')
      // Wikilinks with alias: [[target|alias]] (also the escaped \| used in tables).
      .replace(/\[\[[^\]|]*?\\?\|([^\]]*)\]\]/g, '$1')
      // Wikilinks to a heading: [[note#heading]] → "note › heading".
      .replace(/\[\[([^\]#]*)#([^\]]*)\]\]/g, (_, note, h) => (note ? `${noteName(note)} › ${h}` : h))
      // Plain wikilinks: [[note]] → note.
      .replace(/\[\[([^\]]*)\]\]/g, (_, note) => noteName(note))
      // Relative markdown links: make them work from docs/.
      .replace(/\]\((?!https?:|#|\/)([^)]+)\)/g, (_, path) => `](${linkPrefix}${path})`)
      // Private data.
      .replace(PRIVATE[0], '(private)')
  )
}

mkdirSync(join(root, 'docs'), { recursive: true })
for (const [src, dest, prefix] of NOTES) {
  const header =
    `<!-- Generated by scripts/export-docs.mjs from the author's private notes (${src}). Do not edit by hand. -->\n\n`
  writeFileSync(join(root, 'docs', dest), header + clean(readFileSync(join(root, src), 'utf8'), prefix))
  console.log(`docs/${dest} ← ${src}`)
}
