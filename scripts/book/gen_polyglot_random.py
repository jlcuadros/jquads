#!/usr/bin/env python3
"""
Writes src/book/polyglotRandom.ts: the 781 standard "Random64" numbers of the
Polyglot book format (pieces 0-767, castling 768-771, en passant file
772-779, side to move 780), taken from python-chess (chess.polyglot.POLYGLOT_RANDOM_ARRAY),
so the app computes exactly the same position keys as build_book.py.

Usage (from app/): .venv-book/bin/python scripts/book/gen_polyglot_random.py
"""
import os
import chess.polyglot

OUT = os.path.join(os.path.dirname(__file__), "..", "..", "src", "book", "polyglotRandom.ts")
nums = chess.polyglot.POLYGLOT_RANDOM_ARRAY
assert len(nums) == 781
lines = ",\n".join("  " + ", ".join(f"0x{n:016x}n" for n in nums[i:i + 4]) for i in range(0, len(nums), 4))
with open(OUT, "w") as f:
    f.write("/**\n * The 781 standard Random64 numbers of the Polyglot opening-book format\n"
            " * (pieces 0-767, castling 768-771, en passant 772-779, turn 780).\n"
            " * Generated by scripts/book/gen_polyglot_random.py — do not edit.\n */\n"
            f"export const RANDOM64: readonly bigint[] = [\n{lines},\n]\n")
print(f"wrote {OUT}")
